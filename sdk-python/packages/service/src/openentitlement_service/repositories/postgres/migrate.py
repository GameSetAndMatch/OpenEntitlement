"""Alembic, configured in code from the table definitions in ``tables``.

From the command line, with ``DATABASE_URL`` set::

    python -m openentitlement_service.repositories.postgres.migrate upgrade
    python -m openentitlement_service.repositories.postgres.migrate check
    python -m openentitlement_service.repositories.postgres.migrate revision "add tiers"
"""
from __future__ import annotations

import asyncio
import os
import sys
import threading
from collections.abc import Callable
from pathlib import Path

from alembic import command
from alembic.config import Config

MIGRATIONS = Path(__file__).with_name("migrations")
TRUE = {"1", "true", "yes", "on"}


def alembic_config(url: str, *, transaction_pooler: bool = False) -> Config:
    """Migrations connect with the same engine settings as requests, including the pooler switch."""
    config = Config()
    config.set_main_option("script_location", str(MIGRATIONS))
    config.set_main_option("path_separator", "os")
    config.attributes["url"] = url
    config.attributes["transaction_pooler"] = transaction_pooler
    return config


def _run(fn: Callable[[], object]) -> None:
    """Run an Alembic command, on its own thread when an event loop is already running here."""
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        fn()
        return
    errors: list[BaseException] = []

    def target() -> None:
        try:
            fn()
        except BaseException as exc:  # re-raised on the caller's thread
            errors.append(exc)

    thread = threading.Thread(target=target, name="alembic")
    thread.start()
    thread.join()
    if errors:
        raise errors[0]


def migrate(url: str, *, transaction_pooler: bool = False) -> None:
    """Apply every migration up to the latest one."""
    _run(lambda: command.upgrade(alembic_config(url, transaction_pooler=transaction_pooler), "head"))


def check(url: str) -> None:
    """Raise ``alembic.util.exc.AutogenerateDiffsDetected`` when the tables and migrations drift."""
    _run(lambda: command.check(alembic_config(url)))


def revision(url: str, message: str) -> None:
    """Generate a migration from the difference between the tables and the migrated database."""
    _run(lambda: command.revision(alembic_config(url), message=message, autogenerate=True))


def _cli(argv: list[str]) -> None:
    url = os.environ["DATABASE_URL"]
    match argv:
        case ["upgrade"]:
            migrate(url, transaction_pooler=os.environ.get("OE_DATABASE_TRANSACTION_POOLER", "").lower() in TRUE)
        case ["check"]:
            check(url)
        case ["revision", message]:
            revision(url, message)
        case _:
            sys.exit("usage: migrate upgrade | check | revision MESSAGE")


if __name__ == "__main__":
    _cli(sys.argv[1:])
